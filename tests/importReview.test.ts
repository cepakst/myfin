import { describe, expect, it } from 'vitest';
import { mergeRecords, type ExportRecord } from '../src/core/exportStore.js';
import { readDegiroTable } from '../src/core/exportTables.js';

const rec = (date: string, key: string, time = '10:00'): ExportRecord => ({ date, sortKey: `${date}T${time}`, key, rows: [[key]] });

describe('keepExisting on the boundary day of the stored coverage', () => {
  it('adds export rows of the last covered day that are missing in the stored data (export made during the day)', () => {
    const stored = [rec('2025-06-01', 'a'), rec('2025-06-30', 'b', '09:00')];
    const incoming = [rec('2025-06-30', 'b', '09:00'), rec('2025-06-30', 'c', '15:00'), rec('2025-07-02', 'd')];
    const out = mergeRecords(stored, incoming, { from: '2025-06-30', to: '2025-07-02' }, 'keepExisting', [{ from: '2025-06-01', to: '2025-06-30' }]);
    expect(out.map((r) => r.key).sort()).toEqual(['a', 'b', 'c', 'd']);
  });

  it('does not add rows inside the coverage that are not on its boundary', () => {
    const stored = [rec('2025-06-01', 'a'), rec('2025-06-30', 'b')];
    const incoming = [rec('2025-06-15', 'x'), rec('2025-06-30', 'b')];
    const out = mergeRecords(stored, incoming, { from: '2025-06-15', to: '2025-06-30' }, 'keepExisting', [{ from: '2025-06-01', to: '2025-06-30' }]);
    expect(out.map((r) => r.key).sort()).toEqual(['a', 'b']);
  });

  it('is count-aware on the boundary day (a duplicate already stored once is added once more)', () => {
    const stored = [rec('2025-06-30', 'b')];
    const incoming = [rec('2025-06-30', 'b'), rec('2025-06-30', 'b')];
    const out = mergeRecords(stored, incoming, { from: '2025-06-30', to: '2025-06-30' }, 'keepExisting', [{ from: '2025-06-01', to: '2025-06-30' }]);
    expect(out).toHaveLength(2);
  });
});

describe('Degiro table reader', () => {
  it('skips footer / disclaimer lines instead of rejecting the whole file', () => {
    const csv = [
      'Date,Time,Product,ISIN,Reference exchange,Venue,Quantity,Price,,Local value,,Value EUR,Exchange rate,AutoFX Fee,Transaction and/or third party fees EUR,Total EUR,Order ID',
      '05-01-2024,10:00,ALFA,US0000000001,NSY,XNYS,10,100,USD,-1000,USD,-900,1.1,0,-1,-901,ord-1',
      'Report generated by DEGIRO,,,,,,,,,,,,,,,,',
    ].join('\n');
    const t = readDegiroTable(csv, 'DEGIRO_TX');
    expect(t.records).toHaveLength(1);
    expect(t.warnings.some((w) => w.includes('neplatným datem'))).toBe(true);
  });
});
