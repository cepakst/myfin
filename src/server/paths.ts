import { mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

/** Project root: two levels up from src/server or dist/server */
export const ROOT = resolve(process.env.MYFIN_ROOT ?? join(here, '..', '..'));
export const DATA_DIR = resolve(process.env.MYFIN_DATA ?? join(ROOT, 'data'));
export const CACHE_DIR = join(DATA_DIR, 'cache');
export const SETTINGS_FILE = join(DATA_DIR, 'settings.json');
/** Imported exports split by year (the user's exports folder is only read). Not a cache – never delete. */
export const STORE_DIR = join(DATA_DIR, 'store');
export const DEFAULT_EXPORTS_DIR = resolve(process.env.MYFIN_EXPORTS ?? join(ROOT, 'exports'));
export const WEB_DIST = resolve(process.env.MYFIN_WEB_DIST ?? join(ROOT, 'dist', 'web'));
/** Bundled synthetic demo exports (read-only, generated by scripts/generate-demo.ts) */
export const DEMO_DIR = resolve(process.env.MYFIN_DEMO_DIR ?? join(ROOT, 'demo'));
/** Demo mode keeps its own settings so experiments with demo data never touch the user's real settings */
export const DEMO_SETTINGS_FILE = join(DATA_DIR, 'settings.demo.json');
/** Accounts module configuration (aliases, product types, balances entered by the user, own accounts) */
export const ACCOUNTS_FILE = join(DATA_DIR, 'accounts.json');
export const DEMO_ACCOUNTS_FILE = join(DATA_DIR, 'accounts.demo.json');

export function ensureDir(p: string): string {
  mkdirSync(p, { recursive: true });
  return p;
}
